# ПРАВИЛО ГОЛОСА. У каждой прямой речи Вольфганга есть лицо и курсив. Лицо
# показывает, с каким выражением он это говорит, курсив отделяет его голос от
# всего остального; строка без значка читается как системное сообщение, а не
# как реплика. Всё, что бот сообщает от себя, — счёт, названия, списки,
# счётчики — остаётся прямым и без лица.
#
# Без лица осталось объяснение в настройках — там он говорит один и значку
# нечего противопоставить. Во всплывающих окошках — «квиз уже
# закончился» и тостах настроек — разметка не работает вовсе, так что там
# возможно только обычное эмодзи, без курсива и без кастомного.

# Кастомные эмодзи Вольфганга — смайлики в парике. Набор бот собирает себе сам
# (`python -m tools.add_emoji`), и при каждой пересборке идентификаторы меняются:
# старые перестают работать, так что новые надо переносить сюда целиком.
#
# Эмодзи внутри тега — запасное: его увидят там, где кастомное не отрисуется,
# на старом клиенте или пока у владельца бота нет Premium. Пустой идентификатор
# значит, что картинка ещё не нарисована, и остаётся одно запасное.
def wolfgang(fallback: str, emoji_id: str = "") -> str:
    if not emoji_id:
        return fallback

    return f'<tg-emoji emoji-id="{emoji_id}">{fallback}</tg-emoji>'

