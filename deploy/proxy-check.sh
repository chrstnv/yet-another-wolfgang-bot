#!/bin/sh
# Проверяет, жив ли канал до Телеграма, и поднимает прокси, если он умер.
#
# Отдельно от сторожа за контейнерами потому, что отказ тут особенный: бот
# продолжает работать и выглядеть здоровым, только Телеграм для него исчезает.
# Пожаловаться он тоже не может — жалоба идёт тем же каналом. Значит, замечать
# такое должен кто-то снаружи.
#
# Проверка идёт изнутри контейнера бота: там уже есть и питон, и умение ходить
# через SOCKS, и он видит прокси по имени службы — то есть проверяется ровно
# тот путь, которым ходит сам бот.
set -eu

PROXY="${TELEGRAM_PROXY:-socks5://proxy:1080}"

check() {
    docker exec wolfgang-bot python -c "
import sys, httpx
try:
    httpx.get('https://api.telegram.org/', proxy='$PROXY', timeout=15)
except Exception as error:
    print(error)
    sys.exit(1)
" 2>&1
}

if check > /dev/null 2>&1; then
    exit 0
fi

echo "Телеграм через прокси недоступен: $(check || true)"
echo "Перезапускаю прокси"
docker restart wolfgang-proxy

sleep 10

if check > /dev/null 2>&1; then
    echo "Канал восстановлен"
    exit 0
fi

# Перезапуск не помог: скорее всего сменился адрес узла или кончилась подписка.
# Чинится только руками — заново собрать proxy.json из свежей ссылки
echo "Перезапуск не помог. Похоже, узел провайдера сменился — нужен новый proxy.json"
exit 1
