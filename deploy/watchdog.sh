#!/bin/sh
# Сторож на хосте: перезапускает контейнер, если healthcheck признал его больным.
#
# Нужен потому, что политика перезапуска Docker смотрит только на код возврата
# и на состояние здоровья не реагирует вовсе — контейнер с провалившейся
# проверкой так и висит. Сам бот выходит, когда замечает, что опрос встал; этот
# скрипт закрывает случай, когда встал весь процесс и заметить уже некому.
set -eu

health=$(docker inspect --format '{{.State.Health.Status}}' wolfgang-bot 2>/dev/null || echo "нет контейнера")

case "$health" in
    healthy|starting)
        exit 0
        ;;
    unhealthy)
        echo "Контейнер болен, перезапускаю"
        docker restart wolfgang-bot
        ;;
    *)
        echo "Состояние не определить: $health"
        exit 1
        ;;
esac
